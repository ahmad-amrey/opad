TEST(bar_pulled_along_and_across_its_layers) {
  if (!engines_ok()) return;
  const sim::PrintSettings s = sim::print_settings({{"material", "pla"}});
  const double sigma = 10, phi = s.fill();
  // Flat: the pull runs along the roads; its index (sigma / X)^2.
  std::string bar;
  sim::StudyRun flat = pulled_bar({0, 0, 1}, bar);
  const double along = std::pow(sigma / (phi * s.material.X), 2);
  CHECK_NEAR(sim::probe(*flat.fea, {20, 5, 5}, "failure_index"), along, 0.05 * along);
  CHECK_NEAR(sim::probe(*flat.fea, {20, 5, 5}, "sxx"), sigma, 0.02 * sigma);
  const double e_along = sim::probe(*flat.fea, {30, 5, 5}, "dx") - sim::probe(*flat.fea, {10, 5, 5}, "dx");
  CHECK_NEAR(e_along, sigma * 20 / (phi * s.material.E), 0.02 * sigma * 20 / (phi * s.material.E));
  // (It is weakest where it is held: the end wall's roads run across the pull there.)
  CHECK(flat.summary["print"]["Bar"]["fails"].get<std::string>().find("between layers") == std::string::npos);
  // Standing on its end: the same pull opens the layers; (sigma / Z)^2, and it stretches by the between-layer stiffness.
  sim::StudyRun upright = pulled_bar({1, 0, 0}, bar);
  const double across = std::pow(sigma / (phi * s.material.Z), 2);
  CHECK_NEAR(sim::probe(*upright.fea, {20, 5, 5}, "failure_index"), across, 0.05 * across);  // an index: 2.5 % in stress (the worst element at the node)
  const double e_across = sim::probe(*upright.fea, {30, 5, 5}, "dx") - sim::probe(*upright.fea, {10, 5, 5}, "dx");
  const double kz = s.material.kz;
  CHECK_NEAR(e_across, sigma * 20 / (phi * kz * s.material.E), 0.02 * sigma * 20 / (phi * kz * s.material.E));
  CHECK(upright.summary["print"]["Bar"]["fails"].get<std::string>().find("between layers") == 0);
  CHECK(upright.summary["print"]["Bar"]["min_safety_factor"].get<double>() < flat.summary["print"]["Bar"]["min_safety_factor"].get<double>());
}

TEST(grid_infill_against_explicit_grid_walls) {
  if (!engines_ok()) return;
  // A 48 x 24 x 3 coupon of square cells a = 8 with walls t = 1.2 (rho = 2 t/a - (t/a)^2), stretched 0.1 mm along x: the
  // walls modelled one by one in solid plastic, against the block with the averaged-out grid infill in the same plastic
  // (isotropic roads that fill their box: kt = kz = 1, flow making up the stadium).
  const double L = 48, W = 24, H = 3, a = 8, t = 1.2, E = 3000, nu = 0.35, stretch = 0.1;
  const double rho = 2 * t / a - (t / a) * (t / a);
  auto reaction = [&](bool explicit_walls) {
    Document doc = Document::create();
    std::string body;
    if (explicit_walls) {
      for (double y = a / 2; y < W; y += a) body = box(doc, {0, y - t / 2, 0}, L, t, H, "Grid", body);
      for (double x = a / 2; x < L; x += a) body = box(doc, {x - t / 2, 0, 0}, t, W, H, "Grid", body);
    } else {
      body = box(doc, {0, 0, 0}, L, W, H, "Block");
    }
    commands::run("load", {{"kind", "fixed"}, {"on", {faces_at(body, "x", 0, !explicit_walls)}}}, &doc);
    commands::run("load", {{"kind", "displacement"}, {"on", {faces_at(body, "x", L, !explicit_walls)}}, {"vector", {stretch, 0, 0}}}, &doc);
    json settings = {{"mesh_size", explicit_walls ? 0.8 : 2.0}};
    if (explicit_walls) {
      settings["materials"] = {{"all", {{"E", E}, {"nu", nu}, {"density", 1.24}}}};
    } else {
      settings["print"] = {{"material", {{"base", "pla"}, {"E", E}, {"nu", nu}, {"kt", 1}, {"kz", 1}}}, {"walls", 0}, {"top_layers", 0},
                           {"bottom_layers", 0}, {"infill", rho * 100}, {"pattern", "grid"}, {"infill_angle", 0}, {"flow", 1 / stadium(0.2, 0.45)}};
    }
    const sim::StudyRun run = sim::run_study(doc, resolve(doc), {{"kind", "static"}, {"settings", settings}});
    return std::fabs(run.summary["reactions_N"]["Fixed 1"][0].get<double>());
  };
  const double walls = reaction(true), averaged = reaction(false);
  const double bars = E * (W / a) * t * H * stretch / L;  // the walls along x alone
  CHECK_NEAR(averaged, bars, 0.01 * bars);
  CHECK_NEAR(averaged, walls, 0.05 * walls);
}

