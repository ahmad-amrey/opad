TEST(profiles_from_each_slicer) {
  Dir d;
  // PrusaSlicer: an exported config bundle's print and filament keys; widths as a share of the nozzle.
  json p = sim::read_profile(d.write("prusa.ini", "# generated by PrusaSlicer\nlayer_height = 0.15\nperimeters = 3\ntop_solid_layers = 5\n"
                                                  "bottom_solid_layers = 3\nfill_density = 15%\nfill_pattern = gyroid\nfill_angle = 30\n"
                                                  "perimeter_extrusion_width = 112.5%\nnozzle_diameter = 0.4\nextrusion_multiplier = 0.95\n"
                                                  "filament_type = PETG\n"));
  CHECK_EQ(p["walls"].get<int>(), 3);
  CHECK_EQ(p["top_layers"].get<int>(), 5);
  CHECK_EQ(p["bottom_layers"].get<int>(), 3);
  CHECK_NEAR(p["layer_height"].get<double>(), 0.15, 1e-12);
  CHECK_NEAR(p["line_width"].get<double>(), 0.45, 1e-12);
  CHECK_NEAR(p["infill"].get<double>(), 15, 1e-12);
  CHECK_EQ(p["pattern"].get<std::string>(), std::string("gyroid"));
  CHECK_NEAR(p["infill_angle"].get<double>(), 30, 1e-12);
  CHECK_NEAR(p["flow"].get<double>(), 0.95, 1e-12);
  CHECK_EQ(p["material"].get<std::string>(), std::string("PETG"));
  // OrcaSlicer / Bambu Studio: JSON, values as strings or one-element lists.
  p = sim::read_profile(d.write("orca.json", R"({"layer_height": "0.2", "wall_loops": "4", "top_shell_layers": "6", "bottom_shell_layers": "4",
      "sparse_infill_density": "25%", "sparse_infill_pattern": "grid", "inner_wall_line_width": "0.42", "filament_type": ["PLA-CF"],
      "filament_flow_ratio": ["0.98"]})"));
  CHECK_EQ(p["walls"].get<int>(), 4);
  CHECK_EQ(p["top_layers"].get<int>(), 6);
  CHECK_NEAR(p["line_width"].get<double>(), 0.42, 1e-12);
  CHECK_NEAR(p["infill"].get<double>(), 25, 1e-12);
  CHECK_NEAR(p["flow"].get<double>(), 0.98, 1e-12);
  const sim::PrintSettings orca = sim::print_settings({{"profile", path_to_utf8(d.p / "orca.json")}});
  CHECK_EQ(orca.material.id, std::string("pla-cf"));
  CHECK_EQ(orca.family, std::string("grid"));
  CHECK_NEAR(orca.wall_thickness(), 4 * 0.42, 1e-12);
  // Cura: a quality profile's [values], flow as a percentage.
  p = sim::read_profile(d.write("fine.inst.cfg", "[general]\nversion = 4\nname = Fine\n\n[metadata]\ntype = quality\n\n[values]\n"
                                                 "layer_height = 0.1\nwall_line_count = 2\ntop_layers = 8\nbottom_layers = 6\n"
                                                 "infill_sparse_density = 40\ninfill_pattern = triangles\nwall_line_width = 0.4\n"
                                                 "material_flow = 102\n"));
  CHECK_NEAR(p["layer_height"].get<double>(), 0.1, 1e-12);
  CHECK_EQ(p["top_layers"].get<int>(), 8);
  CHECK_NEAR(p["infill"].get<double>(), 40, 1e-12);
  CHECK_NEAR(p["flow"].get<double>(), 1.02, 1e-12);
  CHECK_EQ(sim::infill_family(p["pattern"].get<std::string>()), std::string("triangles"));
  // G-code: the settings the slicer appended at its end.
  p = sim::read_profile(d.write("part.gcode", "G1 X10 Y10 E1\nG1 X20 Y10 E2\n; prusaslicer_config = begin\n; layer_height = 0.3\n"
                                              "; perimeters = 2\n; fill_density = 50%\n; fill_pattern = honeycomb\n"
                                              "; perimeter_extrusion_width = 0.5\n; prusaslicer_config = end\n"));
  CHECK_NEAR(p["layer_height"].get<double>(), 0.3, 1e-12);
  CHECK_NEAR(p["infill"].get<double>(), 50, 1e-12);
  CHECK_EQ(p["pattern"].get<std::string>(), std::string("honeycomb"));
  // 3MF projects: PrusaSlicer's "; key = value" and Orca's JSON inside the zip.
  {
    std::ofstream(d.p / "prusa.3mf", std::ios::binary)
        << stored_zip({{"3D/3dmodel.model", "<model/>"}, {"Metadata/Slic3r_PE.config", "; perimeters = 5\n; fill_density = 35%\n; fill_pattern = cubic\n"}});
    p = sim::read_profile(d.p / "prusa.3mf");
    CHECK_EQ(p["walls"].get<int>(), 5);
    CHECK_EQ(p["pattern"].get<std::string>(), std::string("cubic"));
    std::ofstream(d.p / "orca.3mf", std::ios::binary)
        << stored_zip({{"3D/3dmodel.model", "<model/>"}, {"Metadata/project_settings.config", R"({"wall_loops": "3", "sparse_infill_density": "10%"})"}});
    p = sim::read_profile(d.p / "orca.3mf");
    CHECK_EQ(p["walls"].get<int>(), 3);
    CHECK_NEAR(p["infill"].get<double>(), 10, 1e-12);
    std::ofstream(d.p / "bare.3mf", std::ios::binary) << stored_zip({{"3D/3dmodel.model", "<model/>"}});
    CHECK_THROWS(sim::read_profile(d.p / "bare.3mf"));
  }
  CHECK_THROWS(sim::read_profile(d.write("empty.ini", "# nothing a slicer wrote\n")));
  CHECK_THROWS(sim::read_profile(d.p / "missing.ini"));
}

