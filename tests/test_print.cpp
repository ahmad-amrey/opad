TEST(road_fill_and_wall_material) {
  // A 0.2 x 0.45 road fills 1 - (1 - pi/4) 0.2 / 0.45 of its box; flow scales it, never past full.
  sim::PrintSettings s = sim::print_settings({{"material", "pla"}});
  CHECK_NEAR(s.fill(), stadium(0.2, 0.45), 1e-12);
  CHECK_NEAR(sim::print_settings({{"flow", 0.9}}).fill(), 0.9 * stadium(0.2, 0.45), 1e-12);
  CHECK_NEAR(sim::print_settings({{"flow", 1.2}}).fill(), 1.0, 1e-12);
  // Walls: the filament's along-road, across-road and between-layer values, times the fill.
  const sim::Filament& f = s.material;
  const sim::Ortho w = sim::region_material(s, sim::Region::Wall);
  const double phi = s.fill();
  CHECK_NEAR(w.E1, phi * f.E, 1e-9);
  CHECK_NEAR(w.E2, phi * f.kt * f.E, 1e-9);
  CHECK_NEAR(w.E3, phi * f.kz * f.E, 1e-9);
  CHECK_NEAR(w.X, phi * f.X, 1e-9);
  CHECK_NEAR(w.Z, phi * f.Z, 1e-9);
  CHECK_NEAR(w.Zc, phi * f.C, 1e-9);
  CHECK_NEAR(w.density, phi * f.density, 1e-12);
}

TEST(skins_are_a_cross_ply_laminate) {
  // Top and bottom layers at 0 and 90 deg: classical lamination theory gives E = (A11^2 - A12^2) / A11 both ways, with
  // A11 = (Q11 + Q22) / 2 and A12 = Q12 of one ply.
  sim::PrintSettings s = sim::print_settings({{"infill_angle", 0}});
  const sim::Filament& f = s.material;
  const double phi = s.fill(), E1 = phi * f.E, E2 = phi * f.kt * f.E, nu12 = f.nu, nu21 = nu12 * E2 / E1;
  const double Q11 = E1 / (1 - nu12 * nu21), Q22 = E2 / (1 - nu12 * nu21), Q12 = nu12 * E2 / (1 - nu12 * nu21);
  const double A11 = (Q11 + Q22) / 2, A12 = Q12;
  const sim::Ortho t = sim::region_material(s, sim::Region::TopBottom);
  CHECK_NEAR(t.E1, (A11 * A11 - A12 * A12) / A11, 1e-6 * t.E1);
  CHECK_NEAR(t.E2, t.E1, 1e-6 * t.E1);
  CHECK_NEAR(t.E3, phi * f.kz * f.E, 1e-9);
  // Pulled along a ply, that ply fails first, at less than the road's strength X (it carries more than its share).
  CHECK(t.X > 0.5 * phi * f.X && t.X < phi * f.X);
  // At +-45 deg: Qbar11 = (Q11 + Q22 + 2 Q12 + 4 Q66) / 4 and Qbar12 = (Q11 + Q22 - 4 Q66) / 4 + Q12 / 2 in both plies.
  const double Q66 = phi * f.kt * f.E / (2 * (1 + f.nu));
  const double B11 = (Q11 + Q22 + 2 * Q12 + 4 * Q66) / 4, B12 = (Q11 + Q22 - 4 * Q66) / 4 + Q12 / 2;
  const sim::Ortho t45 = sim::region_material(sim::print_settings({{"infill_angle", 45}}), sim::Region::TopBottom);
  CHECK_NEAR(t45.E1, (B11 * B11 - B12 * B12) / B11, 1e-6 * t45.E1);
  // 100 % infill is the same laminate (at the infill's own axes).
  const sim::Ortho solid = sim::region_material(sim::print_settings({{"infill", 100}, {"infill_angle", 0}}), sim::Region::Core);
  CHECK_NEAR(solid.E1, t.E1, 1e-6 * t.E1);
}

TEST(infill_models) {
  // A square grid: rho = 2 t/a - (t/a)^2 of plastic, t/a of it along each axis; walls standing the full height.
  const sim::PrintSettings s = sim::print_settings({{"infill", 20}, {"pattern", "grid"}});
  const double rho = 0.2 * s.fill(), ta = 1 - std::sqrt(1 - rho);
  CHECK_NEAR(2 * ta - ta * ta, rho, 1e-12);
  const sim::Ortho g = sim::region_material(s, sim::Region::Core);
  CHECK_NEAR(g.E1, ta * s.material.E, 1e-9);
  CHECK_NEAR(g.E3, rho * s.material.kz * s.material.E, 1e-9);
  CHECK_NEAR(g.G12, ta * ta * ta * s.material.E / 2, 1e-9);  // walls bending between crossings
  CHECK_NEAR(g.density, rho * s.material.density, 1e-12);
  // Stretching patterns are stiffer in plane than bending ones at the same density; every pattern gets stiffer with it.
  auto E1 = [](const char* pattern, double infill) { return sim::region_material(sim::print_settings({{"infill", infill}, {"pattern", pattern}}), sim::Region::Core).E1; };
  CHECK(E1("triangles", 20) > E1("honeycomb", 20));
  CHECK(E1("grid", 20) > E1("gyroid", 20));
  for (const char* p : {"lines", "grid", "triangles", "honeycomb", "cubic", "gyroid", "lightning", "concentric"}) {
    CHECK(E1(p, 40) > E1(p, 10));
    const sim::Ortho o = sim::region_material(sim::print_settings({{"infill", 15}, {"pattern", p}}), sim::Region::Core);
    // An admissible orthotropic material: 1 - nu12 nu21 - ... > 0.
    const double n21 = o.nu12 * o.E2 / o.E1, n31 = o.nu13 * o.E3 / o.E1, n32 = o.nu23 * o.E3 / o.E2;
    CHECK(1 - o.nu12 * n21 - o.nu23 * n32 - o.nu13 * n31 - 2 * n21 * n32 * o.nu13 > 0);
  }
}

TEST(failure_criterion_in_region_axes) {
  const sim::Ortho m = sim::region_material(sim::print_settings(json::object()), sim::Region::Wall);
  const Vec3 x{1, 0, 0}, y{0, 1, 0}, z{0, 0, 1};
  // Uniaxial at each strength: index 1, and the mode that names it.
  sim::Failure f = sim::failure({m.X, 0, 0, 0, 0, 0}, x, y, z, m);
  CHECK_NEAR(f.index, 1, 1e-12);
  CHECK_EQ(f.mode, std::string("along the roads"));
  f = sim::failure({0, m.Y, 0, 0, 0, 0}, x, y, z, m);
  CHECK_NEAR(f.index, 1, 1e-12);
  CHECK_EQ(f.mode, std::string("across the roads"));
  f = sim::failure({0, 0, m.Z, 0, 0, 0}, x, y, z, m);
  CHECK_NEAR(f.index, 1, 1e-12);
  CHECK_EQ(f.mode, std::string("between layers"));
  f = sim::failure({0, 0, 0, 0, 0.5 * m.S23, 0}, x, y, z, m);
  CHECK_NEAR(f.index, 0.25, 1e-12);
  CHECK_EQ(f.mode, std::string("shear"));
  // Pressed together the layers hold: compression across them against the plastic's compressive strength.
  CHECK(m.Zc > m.Z);
  f = sim::failure({0, 0, -m.Z, 0, 0, 0}, x, y, z, m);
  CHECK_NEAR(f.index, std::pow(m.Z / m.Zc, 2), 1e-12);
  f = sim::failure({0, 0, -m.Zc, 0, 0, 0}, x, y, z, m);
  CHECK_NEAR(f.index, 1, 1e-12);
  CHECK_EQ(f.mode, std::string("in compression"));
  // Half the strength: a quarter of the index (safety factor 2).
  CHECK_NEAR(sim::failure({0, 0, 0.5 * m.Z, 0, 0, 0}, x, y, z, m).index, 0.25, 1e-12);
  // Roads at 30 deg in the plane: a pull along them in world axes is a pull along the roads.
  const double c = std::cos(kPi / 6), s = std::sin(kPi / 6);
  const Vec3 a1{c, s, 0}, a2{-s, c, 0};
  f = sim::failure({m.X * c * c, m.X * s * s, 0, m.X * c * s, 0, 0}, a1, a2, z, m);
  CHECK_NEAR(f.index, 1, 1e-9);
  CHECK_EQ(f.mode, std::string("along the roads"));
  // An infill the same every way in its layer (gyroid) fails under the same in-plane pull along its axes or at 45 deg to
  // them, however weak it is between layers (that bond stays out of the layer's own criterion).
  const sim::Ortho g = sim::region_material(sim::print_settings({{"pattern", "gyroid"}, {"infill", 30}}), sim::Region::Core);
  const double r2 = std::sqrt(0.5), p = 0.8 * g.X;
  const double along = sim::failure({p, 0, 0, 0, 0, 0}, x, y, z, g).index, diagonal = sim::failure({p, 0, 0, 0, 0, 0}, {r2, r2, 0}, {-r2, r2, 0}, z, g).index;
  CHECK_NEAR(diagonal, along, 1e-9);
  CHECK_NEAR(along, 0.64, 1e-9);
  // Built on its side (layers stacked along world x): a pull along x is a pull between layers.
  f = sim::failure({m.Z, 0, 0, 0, 0, 0}, y, z, x, m);
  CHECK_NEAR(f.index, 1, 1e-12);
  CHECK_EQ(f.mode, std::string("between layers"));
}

TEST(infill_region_volume) {
  // What a slicer fills: walls in from the sides, top and bottom skins in from the faces looking up and down.
  const sim::PrintSettings s = sim::print_settings({{"walls", 2}, {"line_width", 0.45}, {"top_layers", 4}, {"bottom_layers", 3}, {"layer_height", 0.2}});
  const double tw = 0.9, tt = 0.8, tb = 0.6;
  const TopoDS_Shape core = sim::print_core(BRepPrimAPI_MakeBox(40, 20, 10).Shape(), s);
  CHECK(!core.IsNull());
  CHECK_NEAR(volume(core), (40 - 2 * tw) * (20 - 2 * tw) * (10 - tt - tb), 1e-3);
  const TopoDS_Shape ring = sim::print_core(BRepPrimAPI_MakeCylinder(15, 10).Shape(), s);
  CHECK_NEAR(volume(ring), kPi * (15 - tw) * (15 - tw) * (10 - tt - tb), 1e-3);
  // Built on its side: the skins are across x now.
  sim::PrintSettings side = s;
  side.up = {1, 0, 0};
  CHECK_NEAR(volume(sim::print_core(BRepPrimAPI_MakeBox(40, 20, 10).Shape(), side)), (40 - tt - tb) * (20 - 2 * tw) * (10 - 2 * tw), 1e-3);
  // Thinner than its skins: no infill.
  CHECK(sim::print_core(BRepPrimAPI_MakeBox(40, 20, 1.2).Shape(), s).IsNull());
}

